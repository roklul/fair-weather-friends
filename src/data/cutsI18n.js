// 輔助函式：動態取得本地化細切部位資料
export function getLocalizedCut(cut, currentLang = 'zh-TW') {
  if (!cut) return cut;
  const i18n = CUTS_I18N[cut.id]?.[currentLang];
  if (!i18n) return cut;

  return {
    ...cut,
    name: i18n.name || cut.name,
    aliases: i18n.aka || cut.aliases,
    primalName: i18n.primalName || cut.primalName,
    tagBadge: i18n.tagBadge || cut.tagBadge,
    keywords: i18n.keywords || cut.keywords,
    locationDesc: i18n.locationDesc || cut.locationDesc,
    donenessTip: i18n.donenessTip || cut.donenessTip,
    cookingRecommendations: i18n.cookingRecs || cut.cookingRecommendations || (cut.cookingMethods?.map(m => m.name).join(' · ')),
    winePairingDisplay: i18n.winePairing || cut.winePairing?.wines?.join(' · ') || '',
  };
}

// 輔助函式：動態取得本地化選肉決策助手資料
export function getLocalizedWizardData(wizardData, activeCategory = 'beef', currentLang = 'zh-TW') {
  if (!wizardData) return wizardData;
  const catI18n = WIZARD_I18N[activeCategory];
  if (!catI18n) return wizardData;

  const textures = (wizardData.textures || []).map((t) => {
    const tI18n = catI18n.textures?.[t.id]?.[currentLang];
    return {
      ...t,
      label: tI18n?.label || t.label,
      desc: tI18n?.desc || t.desc,
    };
  });

  const cookingMethods = (wizardData.cookingMethods || []).map((c) => {
    const cI18n = catI18n.cookingMethods?.[c.id]?.[currentLang];
    return {
      ...c,
      label: cI18n?.label || c.label,
      desc: cI18n?.desc || c.desc,
    };
  });

  return {
    ...wizardData,
    textures,
    cookingMethods,
  };
}
